private struct IndependentLogisticCase: Sendable {
    let epochs: Int
    let weights: [Double]
    let bias: Double
    let positiveProbabilities: [Double]
}

private let independentLogisticRows: [[Double]] = [
    [-2.0, -1.0], [0.0, 1.0], [1.0, 2.0], [3.0, 0.0]
]
private let independentLogisticTargets: [Double] = [0.0, 0.0, 1.0, 1.0]
private let independentLogisticCases: [IndependentLogisticCase] = [
    IndependentLogisticCase(
        epochs: 0,
        weights: [0.0, 0.0],
        bias: 0.0,
        positiveProbabilities: [0.5, 0.5, 0.5, 0.5]
    ),
    IndependentLogisticCase(
        epochs: 1,
        weights: [0.1875, 0.0625],
        bias: 0.0,
        positiveProbabilities: [
            0.39233683016710835,
            0.5156199157230156,
            0.5774953651858118,
            0.6370307944803831,
        ]
    ),
    IndependentLogisticCase(
        epochs: 32,
        weights: [1.480821086941844, 0.2239752121236639],
        bias: -0.5291964066127905,
        positiveProbabilities: [
            0.023780679892080436,
            0.42428161759893374,
            0.8021164554146698,
            0.9804160535529572,
        ]
    ),
]

private func independentLogisticBatch() throws -> PreparedNumericBatch {
    try PreparedNumericBatch(
        columnNames: ["x0", "x1"],
        columns: [
            independentLogisticRows.map { $0[0] },
            independentLogisticRows.map { $0[1] },
        ]
    )
}

private func expectClose(
    _ actual: [Double],
    _ expected: [Double],
    tolerance: Double
) {
    #expect(actual.count == expected.count)
    for index in actual.indices where index < expected.count {
        #expect(abs(actual[index] - expected[index]) <= tolerance)
    }
}

private func routedLogisticFixture() throws -> (rows: [[Double]], targets: [Double], batch: PreparedNumericBatch) {
    let rows: [[Double]] = (0..<1_000).map { index -> [Double] in
        let first = Double(index % 17) - 8.0
        let second = Double((index * 7) % 19) - 9.0
        return [first / 4.0, second / 5.0]
    }
    let targets: [Double] = rows.map { row -> Double in
        row[0] * 0.8 - row[1] * 0.35 > 0.15 ? 1.0 : 0.0
    }
    let batch = try PreparedNumericBatch(
        columnNames: ["first", "second"],
        columns: [rows.map { $0[0] }, rows.map { $0[1] }]
    )
    return (rows, targets, batch)
}

@Suite("Prepared logistic regression", .serialized)
struct PreparedLogisticRegressionTests {
    @Test("CPU prepared fit matches independent NumPy reference at 0, 1, and 32 epochs")
    func independentFiniteStepReference() async throws {
        // Values copied from verification/logistic-independent-reference.json,
        // generated by independent NumPy/SciPy full-batch mean BCE updates.
        let batch = try independentLogisticBatch()

        for expected in independentLogisticCases {
            let model = LogisticRegression(device: .cpu)
            try await model.fit(
                features: batch,
                targets: independentLogisticTargets,
                learningRate: 0.25,
                epochs: expected.epochs
            )

            let parameters = await model.getWeightsAndBias()
            let weights = try #require(parameters.weights)
            let bias = try #require(parameters.bias)
            let probabilities = try await model.predictProbability(features: batch)
            let positive = probabilities.map { $0[1] }

            expectClose(weights, expected.weights, tolerance: 1e-14)
            #expect(abs(bias - expected.bias) <= 1e-14)
            expectClose(positive, expected.positiveProbabilities, tolerance: 1e-14)
        }
    }

    @Test("Zero epochs preserves ties and strict thresholds")
    func zeroEpochStrictThreshold() async throws {
        let batch = try independentLogisticBatch()
        let model = LogisticRegression(device: .cpu)
        try await model.fit(
            features: batch,
            targets: independentLogisticTargets,
            learningRate: 0.25,
            epochs: 0
        )

        #expect(try await model.predict(features: batch, threshold: 0.5) == [0, 0, 0, 0])
        #expect(try await model.predict(features: batch, threshold: 0.499) == [1, 1, 1, 1])
        #expect(try await model.predictProbability(features: batch)
            == Array(repeating: [0.5, 0.5], count: 4))
    }

    @Test("Prepared boundaries reject invalid controls, shapes, and values")
    func preparedValidation() async throws {
        let batch = try independentLogisticBatch()
        let targets = independentLogisticTargets

        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: batch, targets: targets, learningRate: 0, epochs: 1
            )
        }
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: batch, targets: targets, learningRate: .nan, epochs: 1
            )
        }
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: batch, targets: targets, learningRate: 0.1, epochs: -1
            )
        }
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: batch, targets: [0.0], learningRate: 0.1, epochs: 1
            )
        }
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: batch,
                targets: [0.0, 0.0, .nan, 1.0],
                learningRate: 0.1,
                epochs: 1
            )
        }

        var missing = batch
        try missing.updateColumn(at: 0, rows: [1], values: [nil])
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: missing, targets: targets, learningRate: 0.1, epochs: 1
            )
        }
        let nonfinite = try PreparedNumericBatch(
            columnNames: ["x0", "x1"],
            columns: [[-2.0, .nan, 1.0, 3.0], [-1.0, 1.0, 2.0, 0.0]]
        )
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: nonfinite, targets: targets, learningRate: 0.1, epochs: 1
            )
        }
        let duplicateNames = try PreparedNumericBatch(
            columnNames: ["x", "x"],
            columns: [[-2.0, 0.0, 1.0, 3.0], [-1.0, 1.0, 2.0, 0.0]]
        )
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: duplicateNames, targets: targets, learningRate: 0.1, epochs: 1
            )
        }
        await #expect(throws: SwiftMLError.self) {
            try await LogisticRegression(device: .cpu).fit(
                features: [[1.0, 2.0], [3.0]],
                targets: [0.0, 1.0],
                learningRate: 0.1,
                epochs: 1
            )
        }

        let fitted = LogisticRegression(device: .cpu)
        try await fitted.fit(features: batch, targets: targets, learningRate: 0.1, epochs: 1)
        let wrongWidth = try PreparedNumericBatch(
            columnNames: ["x0"],
            columns: [[1.0, 2.0]]
        )
        await #expect(throws: SwiftMLError.self) {
            _ = try await fitted.predictProbability(features: wrongWidth)
        }
    }

    @Test("Prepared and row fits preserve finite soft targets")
    func softTargetParity() async throws {
        let rows: [[Double]] = [[-2.0], [-0.5], [0.75], [2.0]]
        let targets: [Double] = [0.1, 0.3, 0.7, 0.9]
        let batch = try PreparedNumericBatch(
            columnNames: ["x"],
            columns: [rows.map { $0[0] }]
        )
        let prepared = LogisticRegression(device: .cpu)
        let legacy = LogisticRegression(device: .cpu)

        try await prepared.fit(
            features: batch, targets: targets, learningRate: 0.2, epochs: 8
        )
        try await legacy.fit(
            features: rows, targets: targets, learningRate: 0.2, epochs: 8
        )

        let preparedParameters = await prepared.getWeightsAndBias()
        let legacyParameters = await legacy.getWeightsAndBias()
        #expect(preparedParameters.weights == legacyParameters.weights)
        #expect(preparedParameters.bias == legacyParameters.bias)
        let preparedProbabilities = try await prepared.predictProbability(features: batch)
        let legacyProbabilities = try await legacy.predictProbability(features: rows)
        #expect(preparedProbabilities == legacyProbabilities)
    }

    @Test("Legacy CPU zero-width and NaN prediction behavior remains available")
    func legacyPredictionContracts() async throws {
        let zeroWidth: [[Double]] = [[], [], []]
        let model = LogisticRegression(device: .cpu)
        try await model.fit(
            features: zeroWidth,
            targets: [0.0, 1.0, 1.0],
            learningRate: 0.25,
            epochs: 1
        )

        let parameters = await model.getWeightsAndBias()
        #expect(parameters.weights == [])
        #expect(abs((parameters.bias ?? .nan) - 1.0 / 24.0) < 1e-15)
        let expectedPositive = 1.0 / (1.0 + exp(-1.0 / 24.0))
        let probabilities = try await model.predictProbability(features: [[], []])
        expectClose(probabilities.map { $0[1] }, [expectedPositive, expectedPositive], tolerance: 1e-15)

        let unfitted = LogisticRegression(device: .cpu)
        #expect(try await unfitted.predict(features: []) == [])
        #expect(try await unfitted.predictProbability(features: []) == [])

        let supplied = LogisticRegression(weights: [1.0], bias: 0.0, device: .cpu)
        let nanProbability = try await supplied.predictProbability(features: [[.nan]])
        #expect(nanProbability == [[0.0, 1.0]])
    }

    @Test("Failed and canceled refits preserve parameters, schema, and device")
    func refitStateIsAtomic() async throws {
        let batch = try independentLogisticBatch()
        let reversed = try PreparedNumericBatch(
            columnNames: ["x1", "x0"],
            columns: [
                independentLogisticRows.map { $0[1] },
                independentLogisticRows.map { $0[0] },
            ]
        )
        let model = LogisticRegression(device: .cpu)
        try await model.fit(
            features: batch,
            targets: independentLogisticTargets,
            learningRate: 0.25,
            epochs: 4
        )
        let originalParameters = await model.getWeightsAndBias()
        let originalProbabilities = try await model.predictProbability(features: batch)
        let originalDevice = await model.resolvedDevice

        let divergent = try PreparedNumericBatch(
            columnNames: ["x0", "x1"],
            columns: [
                [Double.greatestFiniteMagnitude, -Double.greatestFiniteMagnitude],
                [1.0, -1.0],
            ]
        )
        await #expect(throws: SwiftMLError.self) {
            try await model.fit(
                features: divergent,
                targets: [0.0, 1.0],
                learningRate: .greatestFiniteMagnitude,
                epochs: 1
            )
        }
        let parametersAfterFailure = await model.getWeightsAndBias()
        #expect(parametersAfterFailure.weights == originalParameters.weights)
        #expect(parametersAfterFailure.bias == originalParameters.bias)
        #expect(await model.resolvedDevice == originalDevice)
        #expect(try await model.predictProbability(features: batch) == originalProbabilities)
        await #expect(throws: SwiftMLError.self) {
            _ = try await model.predict(features: reversed)
        }

        let cancellation = Task {
            try await model.fit(
                features: batch,
                targets: independentLogisticTargets,
                learningRate: 0.25,
                epochs: 1_000_000
            )
        }
        cancellation.cancel()
        await #expect(throws: CancellationError.self) { try await cancellation.value }

        let parametersAfterCancellation = await model.getWeightsAndBias()
        #expect(parametersAfterCancellation.weights == originalParameters.weights)
        #expect(parametersAfterCancellation.bias == originalParameters.bias)
        #expect(await model.resolvedDevice == originalDevice)
        #expect(try await model.predictProbability(features: batch) == originalProbabilities)
        await #expect(throws: SwiftMLError.self) {
            _ = try await model.predictProbability(features: reversed)
        }
    }

    @Test("Prepared CPU, GPU, auto, and ANE preserve each route's original results")
    func preparedRoutingAgreement() async throws {
        let fixture = try routedLogisticFixture()
        let sampleIndices = Array(0..<16)
        let sampleBatch = try fixture.batch.selectingRows(sampleIndices)
        let sampleRows = Array(fixture.rows.prefix(16))

        // Captured from unchanged e19db7d library objects with pinned MLX.
        // Existing GPU finite-step results differ from CPU; each route has its own oracle.
        let devices: [ExecutionDevice] = [.cpu, .gpu, .auto, .ane]
        for requested in devices {
            let prepared = LogisticRegression(device: requested)
            let rows = LogisticRegression(device: requested)
            try await prepared.fit(
                features: fixture.batch,
                targets: fixture.targets,
                learningRate: 0.05,
                epochs: 4
            )
            try await rows.fit(
                features: fixture.rows,
                targets: fixture.targets,
                learningRate: 0.05,
                epochs: 4
            )

            let expectedRoute: ExecutionDevice = requested == .cpu ? .cpu : .gpu
            #expect(await prepared.resolvedDevice == expectedRoute)
            #expect(await rows.resolvedDevice == expectedRoute)

            let preparedParameters = await prepared.getWeightsAndBias()
            let rowParameters = await rows.getWeightsAndBias()
            let preparedWeights = try #require(preparedParameters.weights)
            let rowWeights = try #require(rowParameters.weights)
            let preparedBias = try #require(preparedParameters.bias)
            let rowBias = try #require(rowParameters.bias)
            let representationTolerance = requested == .cpu ? 0.0 : 1e-6
            expectClose(preparedWeights, rowWeights, tolerance: representationTolerance)
            #expect(abs(preparedBias - rowBias) <= representationTolerance)

            let preparedPositive = try await prepared
                .predictProbability(features: sampleBatch)
                .map { $0[1] }
            let rowPositive = try await rows
                .predictProbability(features: sampleRows)
                .map { $0[1] }
            expectClose(preparedPositive, rowPositive, tolerance: representationTolerance)

            let referenceWeights: [Double] = expectedRoute == .cpu
                ? [0.09696926291864429, -0.02357937780181345]
                : [0.09685021638870239, -0.023611553013324738]
            let referenceBias: Double = expectedRoute == .cpu ? -0.009412758577808177 : 0.014662409201264381
            let referencePositive: [Double] = expectedRoute == .cpu
                ? [
                    0.4598594698166819,
                    0.45768217570120745,
                    0.4555064968639452,
                    0.47561605638900817,
                    0.47342954834858,
                    0.471244058939112,
                    0.49142133886730743,
                    0.4892299597835079,
                    0.48703899456771504,
                    0.5072437890949602,
                    0.5050519207366427,
                    0.5252388293135551,
                    0.5230517417159851,
                    0.520863769765221,
                    0.5409918850176745,
                    0.5388136472494476,
                  ]
                : [
                    0.465918630361557,
                    0.4637186825275421,
                    0.46152010560035706,
                    0.48167216777801514,
                    0.47946465015411377,
                    0.4772578179836273,
                    0.4974622130393982,
                    0.4952514171600342,
                    0.49304085969924927,
                    0.5132573843002319,
                    0.5110477805137634,
                    0.5312288999557495,
                    0.5290260314941406,
                    0.5268220901489258,
                    0.5469293594360352,
                    0.5447370409965515,
                  ]
            let baselineTolerance = expectedRoute == .cpu ? 1e-14 : 1e-6
            expectClose(preparedWeights, referenceWeights, tolerance: baselineTolerance)
            #expect(abs(preparedBias - referenceBias) <= baselineTolerance)
            expectClose(preparedPositive, referencePositive, tolerance: baselineTolerance)
        }
    }

    @Test("Failed automatic GPU refit keeps the previous CPU model and schema")
    func failedRouteChangePreservesState() async throws {
        let batch = try independentLogisticBatch()
        let model = LogisticRegression(device: .auto)
        try await model.fit(features: batch, targets: independentLogisticTargets,
                            learningRate: 0.25, epochs: 1)
        let original = try await model.predictProbability(features: batch)
        let parameters = await model.getWeightsAndBias()
        #expect(await model.resolvedDevice == .cpu)
        let overflow = try PreparedNumericBatch(
            columnNames: ["different", "schema"],
            columns: [Array(repeating: Double.greatestFiniteMagnitude, count: 1_000),
                      Array(repeating: 1.0, count: 1_000)])
        let targets = (0..<1_000).map { index -> Double in Double(index % 2) }
        await #expect(throws: SwiftMLError.self) {
            try await model.fit(features: overflow, targets: targets,
                                learningRate: 0.25, epochs: 1)
        }
        #expect(await model.resolvedDevice == .cpu)
        let after = await model.getWeightsAndBias()
        #expect(after.weights == parameters.weights && after.bias == parameters.bias)
        #expect(try await model.predictProbability(features: batch) == original)
    }
